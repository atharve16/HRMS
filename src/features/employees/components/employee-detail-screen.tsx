"use client";

import { BriefcaseBusiness, CheckCircle2, Pencil, User } from "lucide-react";
import Link from "next/link";
import { useParams, useRouter, useSearchParams } from "next/navigation";

import { PageContainer } from "@/components/layouts/page-container";
import { PageHeader } from "@/components/layouts/page-header";
import { buttonVariants } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { EmployeeInformation } from "@/features/employees/components/employee-information";
import { EmployeeLifecycleDialog } from "@/features/employees/components/employee-lifecycle-dialog";
import { EmployeeErrorState } from "@/features/employees/components/employee-query-state";
import { useDepartment } from "@/features/departments/hooks/use-department";
import { useEmployee } from "@/features/employees/hooks/use-employee";
import { employeeFullName } from "@/features/employees/utils/employee-display";
import { getEmployeeErrorMessage, isEmployeeNotFoundError } from "@/features/employees/utils/employee-errors";
import { EmployeeWorkAssignmentsPanel } from "@/features/work-assignments/components/employee-work-assignments-panel";
import { cn } from "@/lib/utils";

function DetailSkeleton() {
  return (
    <div aria-label="Loading employee" className="space-y-6" role="status">
      <Card><CardContent className="flex gap-4 p-6"><Skeleton className="size-16 rounded-full" /><div className="flex-1 space-y-3"><Skeleton className="h-6 w-56" /><Skeleton className="h-4 w-36" /></div></CardContent></Card>
      <div className="grid gap-6 xl:grid-cols-2">{Array.from({ length: 4 }, (_, index) => <Skeleton className="h-56 rounded-xl" key={index} />)}</div>
      <span className="sr-only">Loading employee details...</span>
    </div>
  );
}

export function EmployeeDetailScreen() {
  const params = useParams<{ employeeId: string }>();
  const router = useRouter();
  const searchParams = useSearchParams();
  const currentTab = searchParams.get("tab") === "assignments" ? "assignments" : "profile";

  const query = useEmployee(params.employeeId);
  const employee = query.data;
  const department = useDepartment(employee?.departmentId ?? "");
  const manager = useEmployee(employee?.reportingManagerId ?? "");
  const successMessage = searchParams.get("created") === "1"
    ? "Employee created successfully. The employee code was generated by the backend."
    : searchParams.get("updated") === "1" ? "Employee information updated successfully." : null;

  function setTab(tab: "profile" | "assignments") {
    const nextParams = new URLSearchParams(searchParams.toString());
    if (tab === "assignments") {
      nextParams.set("tab", "assignments");
    } else {
      nextParams.delete("tab");
    }
    router.replace(`/admin/employees/${params.employeeId}?${nextParams.toString()}`);
  }

  return (
    <PageContainer>
      <PageHeader
        actions={employee ? (
          <div className="flex flex-wrap gap-2">
            <Link className={buttonVariants({ variant: "outline" })} href={`/admin/employees/${employee.id}/edit`}><Pencil aria-hidden="true" className="size-4" />Edit</Link>
            <EmployeeLifecycleDialog employee={employee} />
          </div>
        ) : undefined}
        description="Review employment, contact, reporting, and lifecycle information."
        eyebrow="Employee record"
        title={employee ? employeeFullName(employee) : "Employee details"}
      />
      {successMessage && (
        <div className="mb-6 flex gap-3 rounded-lg border border-success/20 bg-success-soft p-4 text-sm text-success" role="status">
          <CheckCircle2 aria-hidden="true" className="size-5 shrink-0" />{successMessage}
        </div>
      )}

      {employee && (
        <div className="mb-6 flex border-b border-border">
          <button
            className={cn(
              "flex items-center gap-2 border-b-2 px-4 py-2.5 text-sm font-medium transition-colors",
              currentTab === "profile"
                ? "border-primary text-primary font-semibold"
                : "border-transparent text-muted-foreground hover:text-foreground",
            )}
            onClick={() => setTab("profile")}
            type="button"
          >
            <User aria-hidden="true" className="size-4" />
            Profile details
          </button>
          <button
            className={cn(
              "flex items-center gap-2 border-b-2 px-4 py-2.5 text-sm font-medium transition-colors",
              currentTab === "assignments"
                ? "border-primary text-primary font-semibold"
                : "border-transparent text-muted-foreground hover:text-foreground",
            )}
            onClick={() => setTab("assignments")}
            type="button"
          >
            <BriefcaseBusiness aria-hidden="true" className="size-4" />
            Work assignments
          </button>
        </div>
      )}

      {query.isLoading ? <DetailSkeleton /> : query.isError ? (
        isEmployeeNotFoundError(query.error) ? (
          <Card><CardContent className="flex min-h-64 flex-col items-center justify-center text-center"><h2 className="text-lg font-semibold">Employee not found</h2><p className="mt-2 text-sm text-muted-foreground">This employee record may have been removed or the link is invalid.</p><Link className={buttonVariants({ variant: "outline" }) + " mt-5"} href="/admin/employees">Return to directory</Link></CardContent></Card>
        ) : <EmployeeErrorState message={getEmployeeErrorMessage(query.error)} retry={() => query.refetch()} />
      ) : employee ? (
        currentTab === "profile" ? (
          <EmployeeInformation
            departmentName={department.data?.name}
            employee={employee}
            managerName={manager.data ? employeeFullName(manager.data) : undefined}
          />
        ) : (
          <EmployeeWorkAssignmentsPanel
            employeeId={employee.id}
            employeeName={employeeFullName(employee)}
          />
        )
      ) : null}
    </PageContainer>
  );
}
